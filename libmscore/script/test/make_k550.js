// Makes k550.lua, the note list the standalone tests run on, from the playground's embedded score data
// (Mozart, Symphony No. 40, K. 550, i, bars 1-20: public domain), in the form M.setScore takes:
// parts with MuseScore's instrument ids, tie continuations folded into their first notehead.
// Usage: node make_k550.js <playground index.html> > k550.lua
"use strict";
const fs = require("fs");
const html = fs.readFileSync(process.argv[2], "utf8");
const DATA = JSON.parse(/<script[^>]*id="score-data"[^>]*>([\s\S]*?)<\/script>/.exec(html)[1]);
const hostData = require("../../../tools/scripting/playground_engine.js").hostData;   // the playground's own conversion
const KW = new Set(["and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"]);
function lit(v) {
  if (v === null || v === undefined) return "nil";
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  if (typeof v === "string") return JSON.stringify(v);
  if (Array.isArray(v)) return "{" + v.map(lit).join(",") + "}";
  return "{" + Object.keys(v).filter(k => v[k] !== null && v[k] !== undefined).map(k => (/^[A-Za-z_]\w*$/.test(k) && !KW.has(k) ? k : "[" + lit(k) + "]") + "=" + lit(v[k])).join(",") + "}";
}
const d = hostData(DATA);
console.log("-- Mozart, Symphony No. 40 in G minor, K. 550, i, bars 1-20 (flute and strings; public domain): the notes as");
console.log("-- M.setScore takes them. Generated by make_k550.js from the playground's data; don't edit.");
console.log("return {parts=" + lit(d.parts) + ",\nnotes={");
d.notes.forEach(n => console.log(lit(n) + ","));
console.log("}}");
