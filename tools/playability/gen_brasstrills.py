#!/usr/bin/env python3
"""Generate libmscore/playabilitybrasstrills.h (the playability checker's B8 brass trill and two-note tremolo
rules) from b8_rules.py (the owner's approved spec, SPEC-b8.md). Book and page only, no book text.

Checks before writing: every wind id is a playabilitywinds.h key, every Brass name is in playabilityrules.h's
enum, every note name parses, an `unless` names an earlier rule, every text ends with "(solo and section)".

Run:  python3 tools/playability/gen_brasstrills.py
"""
import importlib.util, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
WINDS_H = os.path.join(HERE, '..', '..', 'libmscore', 'playabilitywinds.h')
RULES_H = os.path.join(HERE, '..', '..', 'libmscore', 'playabilityrules.h')
OUT = os.path.join(HERE, '..', '..', 'libmscore', 'playabilitybrasstrills.h')

spec = importlib.util.spec_from_file_location('b8_rules', os.path.join(HERE, 'b8_rules.py'))
R = importlib.util.module_from_spec(spec)
spec.loader.exec_module(R)

STEPS = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
ACC = {'': 0, None: 0, 'b': -1, 'bb': -2, '#': 1, '##': 2}
NONE = -1


def midi(name):
    """'Bb3' -> 58 (C4 = 60)."""
    m = re.fullmatch(r'([A-G])(bb|b|##|#)?(-?\d+)', name)
    if not m:
        sys.exit('bad note name ' + name)
    return 12 * (int(m.group(3)) + 1) + STEPS[m.group(1)] + ACC[m.group(2)]


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


WIND_IDS = set(re.findall(r'\{ "([^"]+)", \{ -?\d+, (?:true|false),', open(WINDS_H).read()))
enum = re.search(r'enum class Brass : char \{([^}]*)\}', open(RULES_H).read()).group(1)
BRASS = {x.strip() for x in enum.split(',') if x.strip()}
GROUPS = {'trumpets': 'B8_TRUMPETS', 'horn': 'B8_HORN', 'low': 'B8_LOW', 'trombones': 'B8_TROMBONES'}
KINDS = {'warning': 'WARNING', 'note': 'NOTE'}
FIELDS = {'id', 'groups', 'pitch', 'kind', 'what', 'pairs', 'at_least', 'valves', 'unless', 'text', 'source'}

for i in R.TRUMPETS + R.HORNS:
    if i not in WIND_IDS:
        sys.exit('%s is not in playabilitywinds.h' % i)
for b in R.LOW + R.TROMBONES:
    if b not in BRASS:
        sys.exit('%s is not a Brass type' % b)

rows, ids = [], []
for r in R.RULES:
    unknown = set(r) - FIELDS
    if unknown:
        sys.exit('%s: unknown fields %s' % (r['id'], unknown))
    assert r['pitch'] in ('sounding', 'written'), r['id']
    assert r['kind'] in KINDS, r['id']
    assert r['what'] in ('trill', 'tremolo', 'both'), r['id']
    if not r['text'].endswith('(solo and section)'):
        sys.exit('%s: every text ends with "(solo and section)"' % r['id'])
    if 'valves' in r and r['what'] != 'trill':
        sys.exit('%s: valves are for trills only' % r['id'])
    for u in r.get('unless', []):
        if u not in ids:
            sys.exit('%s: unless %s is not an earlier rule' % (r['id'], u))
    mask = ' | '.join(GROUPS[g] for g in r['groups'])
    pairs = ', '.join('{ %d, %d }' % (midi(a), midi(b)) for a, b in r.get('pairs', []))
    vlo, vhi = r.get('valves', (NONE, NONE))
    vhi = NONE if vhi is None else vhi
    unless = ', '.join(str(ids.index(u)) for u in r.get('unless', []))
    rows.append('      { %s, %s, %s, BrassTrillKind::%s, %s, %s,\n'
                '        { %s }, %d, %d, %d, { %s },\n'
                '        %s,\n'
                '        %s },'
                % (cstr(r['id']), mask, 'true' if r['pitch'] == 'written' else 'false', KINDS[r['kind']],
                   'true' if r['what'] != 'tremolo' else 'false', 'true' if r['what'] != 'trill' else 'false',
                   pairs, r.get('at_least', NONE), vlo, vhi, unless, cstr(r['text']), cstr(r['source'])))
    ids.append(r['id'])

out = '''//=============================================================================
//  MuseScore
//  Music Composition & Notation
//
//  Playability checker: B8 brass trill and two-note tremolo rules.
//  GENERATED by tools/playability/gen_brasstrills.py from tools/playability/b8_rules.py.
//  Do not edit by hand.
//
//  This program is free software; you can redistribute it and/or modify
//  it under the terms of the GNU General Public License version 2
//  as published by the Free Software Foundation and appearing in
//  the file LICENCE.GPL
//=============================================================================

#ifndef __PLAYABILITYBRASSTRILLS_H__
#define __PLAYABILITYBRASSTRILLS_H__

#include <utility>
#include <vector>
#include "playabilityrules.h"

namespace Ms {

// a mark (warning) with its row, or a note in the panel only
enum class BrassTrillKind { WARNING, NOTE };

// the instrument groups (b8_rules.py): a bit each
enum : int { B8_TRUMPETS = 1, B8_HORN = 2, B8_LOW = 4, B8_TROMBONES = 8 };

// trumpets and horn by their playabilitywinds.h id; euphonium, tubas and trombones by the diagrams' Brass type
inline const std::vector<const char*>& b8TrumpetIds()
      {
      static const std::vector<const char*> ids = { %s };
      return ids;
      }

inline const std::vector<const char*>& b8HornIds()
      {
      static const std::vector<const char*> ids = { %s };
      return ids;
      }

inline const std::vector<Playability::Brass>& b8LowTypes()
      {
      static const std::vector<Playability::Brass> types = { %s };
      return types;
      }

inline const std::vector<Playability::Brass>& b8TromboneTypes()
      {
      static const std::vector<Playability::Brass> types = { %s };
      return types;
      }

// MIDI numbers and semitones; -1 = the field is not used
struct BrassTrillRule {
      const char* id;
      int groups;                            // B8_* bits
      bool written;                          // pitches are written (sounding - WindData::tr)
      BrassTrillKind kind;
      bool trill, tremolo;                   // what it applies to
      std::vector<std::pair<int, int>> pairs; // trill main, upper; tremolo either order; empty: any
      int atLeast;                           // the notes this many semitones or more apart
      int valvesLo, valvesHi;                // trill: fingerings differing in lo..hi valves (hi -1: no top)
      std::vector<int> unless;               // indices of earlier rules: one of them hit, this one is not checked
      const char* text;
      const char* source;                    // book and page
      };

inline const std::vector<BrassTrillRule>& brassTrillRules()
      {
      static const std::vector<BrassTrillRule> rules = {
%s
            };
      return rules;
      }

}     // namespace Ms
#endif
''' % (', '.join(cstr(i) for i in R.TRUMPETS), ', '.join(cstr(i) for i in R.HORNS),
       ', '.join('Playability::Brass::' + b for b in R.LOW), ', '.join('Playability::Brass::' + b for b in R.TROMBONES),
       '\n'.join(rows))

open(OUT, 'w').write(out)
print('wrote', os.path.normpath(OUT), len(rows), 'rules')
