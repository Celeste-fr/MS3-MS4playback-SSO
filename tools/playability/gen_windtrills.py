#!/usr/bin/env python3
"""Generate libmscore/playabilitywindtrills.h (the playability checker's W5 woodwind trill and two-note
tremolo rules) from w5_rules.py (the owner's approved spec, SPEC-w5.md). Book and page only, no book text.

Checks before writing: every instrument id is a playabilitywinds.h key, every note name parses, an
exclusive rule comes before every other rule of its instruments, and every mark's text says
"(solo and section)".

Run:  python3 tools/playability/gen_windtrills.py
"""
import importlib.util, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
WINDS_H = os.path.join(HERE, '..', '..', 'libmscore', 'playabilitywinds.h')
OUT = os.path.join(HERE, '..', '..', 'libmscore', 'playabilitywindtrills.h')

spec = importlib.util.spec_from_file_location('w5_rules', os.path.join(HERE, 'w5_rules.py'))
R = importlib.util.module_from_spec(spec)
spec.loader.exec_module(R)

STEPS = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
ACC = {'': 0, None: 0, 'b': -1, 'bb': -2, '#': 1, '##': 2}
TOP = 127
NONE = -1


def midi(name):
    """'Bb3' -> 58, 'F#3' -> 54 (C4 = 60)."""
    m = re.fullmatch(r'([A-G])(bb|b|##|#)?(-?\d+)', name)
    if not m:
        sys.exit('bad note name ' + name)
    return 12 * (int(m.group(3)) + 1) + STEPS[m.group(1)] + ACC[m.group(2)]


def pc(name):
    """'Db' -> 1"""
    m = re.fullmatch(r'([A-G])(bb|b|##|#)?', name)
    if not m:
        sys.exit('bad pitch class ' + name)
    return (STEPS[m.group(1)] + ACC[m.group(2)]) % 12


def band(b):
    if b is None:
        return NONE, NONE
    lo = midi(b[0])
    hi = midi(b[1]) if b[1] else TOP
    assert lo <= hi, b
    return lo, hi


TR = {k: int(v) for k, v in re.findall(r'\{ "([^"]+)", \{ (-?\d+), (?:true|false),', open(WINDS_H).read())}
KINDS = {'warning': 'WARNING', 'red': 'RED', 'note': 'NOTE'}
FIELDS = {'what', 'pair', 'main', 'main_pcs', 'note', 'wider', 'lower'}


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def clause(c):
    unknown = set(c) - FIELDS
    if unknown:
        sys.exit('unknown clause fields %s' % unknown)
    what = c['what']
    assert what in ('trill', 'tremolo', 'both'), what
    if ('main' in c or 'main_pcs' in c) and what != 'trill':
        sys.exit('main / main_pcs are for trills only')
    if ('wider' in c or 'lower' in c) and what != 'tremolo':
        sys.exit('wider / lower are for tremolos only')
    a, b = (midi(c['pair'][0]), midi(c['pair'][1])) if 'pair' in c else (NONE, NONE)
    mlo, mhi = band(c.get('main'))
    mask = 0
    for p in c.get('main_pcs', []):
        mask |= 1 << pc(p)
    nlo, nhi = band(c.get('note'))
    llo, lhi = band(c.get('lower'))
    return ('{ %s, %s, %d, %d, %d, %d, 0x%03x, %d, %d, %d, %d, %d }'
            % ('true' if what != 'tremolo' else 'false', 'true' if what != 'trill' else 'false',
               a, b, mlo, mhi, mask, nlo, nhi, c.get('wider', NONE), llo, lhi))


rows = []
seen = {}                     # instrument -> index of its first rule
for k, r in enumerate(R.RULES):
    for i in r['instruments']:
        if i not in TR:
            sys.exit('%s: %s is not in playabilitywinds.h' % (r['id'], i))
        if r.get('exclusive') and i in seen:
            sys.exit('%s: an exclusive rule must come first for %s' % (r['id'], i))
        seen.setdefault(i, k)
    assert r['pitch'] in ('sounding', 'written'), r['id']
    assert r['kind'] in KINDS, r['id']
    if r['kind'] != 'note' and '(solo and section)' not in r['text']:
        sys.exit('%s: a mark says "(solo and section)"' % r['id'])
    clauses = ',\n            '.join(clause(c) for c in r['clauses'])
    exc = ', '.join('{ %d, %d }' % (midi(a), midi(b)) for a, b in r.get('except_', []))
    pn = r.get('pair_note')
    pa, pb, ptext = (midi(pn[0][0]), midi(pn[0][1]), cstr(pn[1])) if pn else (NONE, NONE, 'nullptr')
    rows.append('      { %s, { %s }, %s, WindTrillKind::%s,\n'
                '        { %s },\n'
                '        { %s }, %d, %d, %s, %s,\n'
                '        %s,\n'
                '        %s },'
                % (cstr(r['id']), ', '.join(cstr(i) for i in r['instruments']),
                   'true' if r['pitch'] == 'written' else 'false', KINDS[r['kind']],
                   clauses, exc, pa, pb, ptext, 'true' if r.get('exclusive') else 'false',
                   cstr(r['text']), cstr(r['source'])))

out = '''//=============================================================================
//  MuseScore
//  Music Composition & Notation
//
//  Playability checker: W5 woodwind trill and two-note tremolo rules.
//  GENERATED by tools/playability/gen_windtrills.py from tools/playability/w5_rules.py.
//  Do not edit by hand.
//
//  This program is free software; you can redistribute it and/or modify
//  it under the terms of the GNU General Public License version 2
//  as published by the Free Software Foundation and appearing in
//  the file LICENCE.GPL
//=============================================================================

#ifndef __PLAYABILITYWINDTRILLS_H__
#define __PLAYABILITYWINDTRILLS_H__

#include <utility>
#include <vector>

namespace Ms {

// a mark (warning / red) with its row, or a note in the panel only
enum class WindTrillKind { WARNING, RED, NOTE };

// MIDI numbers, both ends of a band included; -1 = the field is not used
struct WindTrillClause {
      bool trill, tremolo;          // what it applies to
      int pairA, pairB;             // trill: main A, upper B; tremolo: A and B in either order
      int mainLo, mainHi;           // trill: the main note in the band
      int mainPcs;                  // trill: the main note's pitch class in this mask (bit 0 = C); 0 unused
      int noteLo, noteHi;           // a note of the trill (main or upper) or tremolo in the band
      int wider;                    // tremolo: notes more than this many semitones apart
      int lowerLo, lowerHi;         // tremolo: the lower note in the band
      };

struct WindTrillRule {
      const char* id;
      std::vector<const char*> instruments;  // playabilitywinds.h ids
      bool written;                          // pitches are written (sounding - WindData::tr)
      WindTrillKind kind;
      std::vector<WindTrillClause> clauses;  // the rule hits when any clause holds
      std::vector<std::pair<int, int>> except;  // trill pairs (main, upper) never hit
      int notePairA, notePairB;              // for this pair (either order for a tremolo) ...
      const char* pairText;                  // ... the message adds this (nullptr: none)
      bool exclusive;                        // a trill or tremolo it hits is not checked by later rules
      const char* text;
      const char* source;                    // book and page
      };

inline const std::vector<WindTrillRule>& windTrillRules()
      {
      static const std::vector<WindTrillRule> rules = {
%s
            };
      return rules;
      }

}     // namespace Ms
#endif
''' % '\n'.join(rows)

open(OUT, 'w').write(out)
print('wrote', os.path.normpath(OUT), len(rows), 'rules')
