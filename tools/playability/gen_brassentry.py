#!/usr/bin/env python3
"""Generate libmscore/playabilitybrassentry.h (the playability checker's B3 brass entrance and leap rules)
from b3_rules.py (the owner's approved spec, SPEC-b3.md). Book and page only, no book text.

Checks before writing: every instrument id is a playabilitywinds.h key, every note name parses, an entry
rule has 'above' and no leap fields, a leap rule has a direction and no 'above', and every text ends with
"(solo and section)" (B3-D8).

Run:  python3 tools/playability/gen_brassentry.py
"""
import importlib.util, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
WINDS_H = os.path.join(HERE, '..', '..', 'libmscore', 'playabilitywinds.h')
OUT = os.path.join(HERE, '..', '..', 'libmscore', 'playabilitybrassentry.h')

spec = importlib.util.spec_from_file_location('b3_rules', os.path.join(HERE, 'b3_rules.py'))
R = importlib.util.module_from_spec(spec)
spec.loader.exec_module(R)

STEPS = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
ACC = {'': 0, None: 0, 'b': -1, 'bb': -2, '#': 1, '##': 2}
NONE = -1


def midi(name):
    """'Bb0' -> 22, 'G5' -> 79 (C4 = 60)."""
    m = re.fullmatch(r'([A-G])(bb|b|##|#)?(-?\d+)', name)
    if not m:
        sys.exit('bad note name ' + name)
    return 12 * (int(m.group(3)) + 1) + STEPS[m.group(1)] + ACC[m.group(2)]


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


TR = {k: int(v) for k, v in re.findall(r'\{ "([^"]+)", \{ (-?\d+), (?:true|false),', open(WINDS_H).read())}
KINDS = {'warning': 'WARNING', 'red': 'RED', 'note': 'NOTE'}
FIELDS = {'id', 'instruments', 'pitch', 'kind', 'what', 'above', 'up', 'down', 'slurred', 'to', 'text', 'source'}
LEAP_FIELDS = {'up', 'down', 'slurred', 'to'}

rows = []
for r in R.RULES:
    unknown = set(r) - FIELDS
    if unknown:
        sys.exit('%s: unknown fields %s' % (r['id'], unknown))
    for i in r['instruments']:
        if i not in TR:
            sys.exit('%s: %s is not in playabilitywinds.h' % (r['id'], i))
    assert r['pitch'] in ('sounding', 'written'), r['id']
    assert r['kind'] in KINDS, r['id']
    if not r['text'].endswith('(solo and section)'):
        sys.exit('%s: the text ends with "(solo and section)" (B3-D8)' % r['id'])
    if r['what'] == 'entry':
        if 'above' not in r or LEAP_FIELDS & set(r):
            sys.exit('%s: an entry rule has above and no leap fields' % r['id'])
        above, up, down, lo, hi = midi(r['above']), NONE, NONE, NONE, NONE
    elif r['what'] == 'leap':
        if 'above' in r or (r.get('up') is None and r.get('down') is None):
            sys.exit('%s: a leap rule has up or down and no above' % r['id'])
        above = NONE
        up = r['up'] if r.get('up') is not None else NONE
        down = r['down'] if r.get('down') is not None else NONE
        assert up == NONE or up > 0, r['id']
        assert down == NONE or down > 0, r['id']
        lo, hi = (midi(r['to'][0]), midi(r['to'][1])) if 'to' in r else (NONE, NONE)
        assert lo <= hi, r['id']
    else:
        sys.exit('%s: what is entry or leap' % r['id'])
    rows.append('      { %s, { %s }, %s, BrassEntryKind::%s, %s,\n'
                '        %d, %d, %d, %s, %d, %d,\n'
                '        %s,\n'
                '        %s },'
                % (cstr(r['id']), ', '.join(cstr(i) for i in r['instruments']),
                   'true' if r['pitch'] == 'written' else 'false', KINDS[r['kind']],
                   'true' if r['what'] == 'leap' else 'false',
                   above, up, down, 'true' if r.get('slurred') else 'false', lo, hi,
                   cstr(r['text']), cstr(r['source'])))

out = '''//=============================================================================
//  MuseScore
//  Music Composition & Notation
//
//  Playability checker: B3 brass entrance and leap rules.
//  GENERATED by tools/playability/gen_brassentry.py from tools/playability/b3_rules.py.
//  Do not edit by hand.
//
//  This program is free software; you can redistribute it and/or modify
//  it under the terms of the GNU General Public License version 2
//  as published by the Free Software Foundation and appearing in
//  the file LICENCE.GPL
//=============================================================================

#ifndef __PLAYABILITYBRASSENTRY_H__
#define __PLAYABILITYBRASSENTRY_H__

#include <vector>

namespace Ms {

// a mark (warning / red) with its row, or a note in the panel only
enum class BrassEntryKind { WARNING, RED, NOTE };

// MIDI numbers and semitones; -1 = the field is not used
struct BrassEntryRule {
      const char* id;
      std::vector<const char*> instruments;  // playabilitywinds.h ids
      bool written;                          // pitches are written (sounding - WindData::tr)
      BrassEntryKind kind;
      bool leap;                             // false: an entrance rule; true: a leap rule
      int above;                             // entrance: a note strictly above this hits
      int up, down;                          // leap: this many semitones or more up / down hits
      bool slurred;                          // leap: both notes under one slur
      int toLo, toHi;                        // leap: the second note in this band (both ends included)
      const char* text;
      const char* source;                    // book and page
      };

inline const std::vector<BrassEntryRule>& brassEntryRules()
      {
      static const std::vector<BrassEntryRule> rules = {
%s
            };
      return rules;
      }

}     // namespace Ms
#endif
''' % '\n'.join(rows)

open(OUT, 'w').write(out)
print('wrote', os.path.normpath(OUT), len(rows), 'rules')
